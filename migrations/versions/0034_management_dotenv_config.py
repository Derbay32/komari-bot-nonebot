"""Retire PostgreSQL management configuration in favor of dotenv.

Operators must provision KOMARI_MANAGEMENT_* startup settings before upgrading.
This migration neither exports credentials nor modifies business storage.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from alembic import op

if TYPE_CHECKING:
    from collections.abc import Sequence

revision: str = "0034"
down_revision: str | Sequence[str] | None = "0033"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None


def upgrade(name: str = "") -> None:
    if name:
        return
    # Handwritten: metadata-external tables are protected from autogenerated drops.
    op.execute('DROP TABLE "komari_management_config"')


def downgrade(name: str = "") -> None:
    if name:
        return
    msg = (
        "0034_MANAGEMENT_CONFIG_IS_IRREVERSIBLE: configure KOMARI_MANAGEMENT_* "
        "startup settings and repair forward; retired credentials cannot be restored."
    )
    raise RuntimeError(msg)
